"""Capture the evidence the demo page renders. Nothing on that page is written by hand.

    python3 -m examples.demo_capture --out docs/demo/evidence.json

Three kinds of capture, labelled as such in the output because they are not
equally strong:

* `live`      - real traffic over the public relay, using only open operations.
* `local`     - a relay, a worker and a demonstration issuer started here, so
                the gated exchanges are reproducible by anyone running this file.
* `computed`  - results calculated directly against a database on this machine,
                for data this town does not serve over the relay.

Local filesystem paths are stripped from the output, since the file is published.

The demonstration issuer's public key is published in the output so a reader can
verify every signature in the transcript for themselves.
"""

